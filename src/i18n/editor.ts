const DICTIONARIES: Record<Language, Dictionary> = { en, nl, pl, tr };
export const EDITOR_DICTIONARIES = DICTIONARIES;

/** The editor follows the Home Assistant user's language, then the card language. */
export function editorLanguage(hass: Pick<HomeAssistant, 'locale'>, cardLanguage?: Language): Language {
  const user = hass.locale?.language?.split('-')[0];
  return user && user in DICTIONARIES ? (user as Language) : cardLanguage ?? 'en';
}

export function et(language: Language, key: EditorKey, values: Record<string, string | number> = {}): string {
  return (DICTIONARIES[language] ?? en)[key].replace(/\{(\w+)\}/g, (match, name: string) => (values[name] !== undefined ? String(values[name]) : match));
}
